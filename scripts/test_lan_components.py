def test_nexus_manager():
    cands = [
        os.path.join(os.getcwd(), "nexus", "NexusAI_Mobile_Client.apk"),
        r"C:\Users\Reader-Branch\Desktop\NexusSuite\dist\4_NexusAI_Mobile_Client.apk"
    ]
    found = None
    for c in cands:
        if os.path.exists(c):
            found = c
            break
    assert found is not None, "Nexus APK not found"
    print("Found Nexus APK:", found, "Size:", os.path.getsize(found))

def test_qr_payload():
    rand_id = secrets.token_hex(2).upper()
    service_name = f"GNDROiD-{rand_id}"
    password = f"{random.randint(100000, 999999)}"
    payload = f"WIFI:T:ADB;S:{service_name};P:{password};;"
    qr = qrcode.QRCode(box_size=5, border=2)
    qr.add_data(payload)
    qr.make(fit=True)
    img = qr.make_image(fill_color="#0f172a", back_color="#ffffff")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    val = buf.getvalue()
    assert len(val) > 200, "PNG generation failed"
    print("QR Payload:", payload, "Generated bytes:", len(val))

